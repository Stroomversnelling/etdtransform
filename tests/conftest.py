def spread_average(frame, cadence, diff_col, grid_minutes=5, drop_na=True):
    """The averaging's spreading, on a frame too short for its presence gates.

    Prepares exactly as :func:`etdtransform.impute.calculate_average_diff_ibis`
    does -- the register supplies the volume for every household with usable
    readings of it, the interval column for the rest -- then calls the spreading
    directly with a one-slot window, which neutralises the gates. That is what
    lets a case be written as six rows with the expected values spelled out.

    Handing the register in unconditionally would agree with the expectation for
    the wrong reason, so the source selection is reproduced rather than assumed.
    Behaviour with the gates applied is tested in
    ``test_minimum_household_presence.py``; behaviour over a realistic span in
    ``test_averaging_coarse_delivery.py``.

    *grid_minutes* is the spacing the rows sit on. Pass a dict of
    ``ProjectIdBSV -> minutes`` for a frame whose projects sit on different
    grids: each project is then spread over its own slots, one pass per distinct
    grid, which is what the averaging itself does. A scalar means every project
    shares that grid.

    Returns ``(avg, coverage, duty)``.
    """
    import ibis

    from etdmap.data_model import cumulative_column
    from etdtransform.impute import _resample_average_ibis

    cum_col = cumulative_column(diff_col)
    minutes = dict(
        zip(cadence[ids.HOUSEHOLD_BATCH], cadence["cadence_minutes"])
    )
    has_register = (
        frame[cum_col].notna() if cum_col in frame.columns
        else pd.Series(False, index=frame.index)
    )
    on_register = frame[ids.HOUSEHOLD].isin(
        frame.loc[has_register, ids.HOUSEHOLD].unique()
    )
    source = (
        frame[cum_col].where(on_register, frame[diff_col])
        if cum_col in frame.columns else frame[diff_col]
    )
    coarsest = max(cadence["cadence_minutes"].dropna())
    projects = sorted(int(p) for p in frame[ids.PROJECT].dropna().unique())
    grids = (
        {int(p): float(m) for p, m in grid_minutes.items()}
        if isinstance(grid_minutes, dict)
        else {p: float(grid_minutes) for p in projects}
    )
    by_grid = {}
    for project in projects:
        by_grid.setdefault(grids[project], []).append(project)

    assigned = frame.assign(
        _value=source.astype("Float64"),
        _minutes=frame[ids.HOUSEHOLD_BATCH].map(minutes).astype("Float64"),
        _on_cumulative=on_register.astype("boolean"),
    )

    frames = []
    total = present = consuming = 0
    for grid, group in sorted(by_grid.items()):
        rows = assigned[assigned[ids.PROJECT].isin(group)]
        total_slots = int(
            rows[[ids.PROJECT, "ReadingDate"]].drop_duplicates().shape[0]
        )
        avg, _coverage, _duty, _presence = _resample_average_ibis(
            ibis.memtable(rows), diff_col, ids.PROJECT, grid,
            max_slots=max(1, int(round(float(coarsest) / grid))),
            total_slots=total_slots,
            window_minutes=grid,
            # Both presence gates neutralised, not just the coverage one: these
            # frames are a handful of rows so a case can be spelled out, and the
            # household floor would empty every one of them. The floor itself is
            # tested at its production value in test_minimum_household_presence.
            min_eligible=1,
        )
        values = avg[f"{diff_col}_avg"]
        total += total_slots
        present += int(values.notna().sum())
        consuming += int((values.fillna(0) > 0).sum())
        frames.append(avg)

    out = pd.concat(frames, ignore_index=True).sort_values(
        [ids.PROJECT, "ReadingDate"]
    )
    if drop_na:
        out = out[out[f"{diff_col}_avg"].notna()]
    return (
        out.reset_index(drop=True),
        float(present / total) if total else 0.0,
        float(consuming / present) if present else 0.0,
    )


def project_averages(df, project_id_column, diff_columns, **kwargs):
    """The project averages of a pandas frame, through the averaging the
    pipeline runs.

    The averaging is ibis, so a test asserting on averaging behaviour has to go
    through ibis or it is asserting about something production does not
    execute. The frames here are small and built in memory, which is what
    ``ibis.memtable`` is for -- the lazy table the pipeline passes comes from
    ``ibis.read_parquet`` instead.

    Takes and returns what :func:`etdtransform.impute.calculate_average_diff_ibis`
    takes and returns, so a test reads as the call it is making.
    """
    import ibis

    from etdtransform.impute import calculate_average_diff_ibis

    return calculate_average_diff_ibis(
        ibis.memtable(df), project_id_column, diff_columns, **kwargs
    )


def cadence_table(df, columns, minutes=5):
    """A cadence table declaring *minutes* for each of *df*'s datasets.

    Imputation scales every threshold to the cadence the column reports at, and
    an absent cadence is an error rather than an assumed grid. A synthetic frame
    is built at a known spacing, so it declares that spacing here.

    Keyed on ``HuisBatchIdBSV``, as the sidecar the mapping writes is: cadence
    is measured on one dataset, against the grid that dataset declares.

    Parameters
    ----------
    df : pd.DataFrame
        Must contain ``HuisBatchIdBSV``.
    columns : iterable of str
        Cumulative column names. Cadence is recorded under the delivered name,
        which is the cumulative side of the pair.
    minutes : float
        The spacing *df* was built at.

    Carries the cadence columns only, with no ``n_readings``. That absence is
    load-bearing: ``bounds.delivered_by_household_batch`` answers "nothing is
    known about delivery" for a table without the field and "delivered
    nothing" for one that has it empty, and the two route differently. A table
    stating a reading count has to say what it was, so a test that needs one
    builds it with :func:`etdmap.testing.cadence_sidecar`.
    """
    batches = sorted(int(b) for b in df[ids.HOUSEHOLD_BATCH].dropna().unique())
    return sidecar_frame(
        "cadence",
        [
            {ids.HOUSEHOLD_BATCH: batch, "column": column,
             "cadence_minutes": minutes}
            for batch in batches
            for column in columns
        ],
        partial=[ids.HOUSEHOLD_BATCH, "column", "cadence_minutes"],
    )
