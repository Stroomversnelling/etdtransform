    old_etdtransform = etdtransform.options.mapped_folder_path
    etdmap.options.mapped_folder_path = target
    etdtransform.options.mapped_folder_path = target
    try:
        yield target
    finally:
        etdmap.options.mapped_folder_path = old_etdmap
        etdtransform.options.mapped_folder_path = old_etdtransform


